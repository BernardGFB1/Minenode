"""Minecraft-aware TCP reverse proxy.

All servers share one public port. The proxy reads the Handshake packet, extracts the hostname
the player typed (e.g. ``survival.mc.example.com``) and forwards the connection to the matching
server's internal port. Offline servers get a friendly status/disconnect message generated by the
proxy itself, and players attempting to join are recorded (whitelist requests, start-on-join).
"""
from __future__ import annotations

import asyncio
import base64
import contextlib
import hmac
import re
import ipaddress
import json
import logging
import socket
import struct
import sys
import time
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .manager import Manager, ServerInstance

log = logging.getLogger("minenode.proxy")

HANDSHAKE_TIMEOUT = 8
MAX_HANDSHAKE = 2048
PROXY_V2_SIG = b"\r\n\r\n\x00\r\nQUIT\n"
TCP_CONNECTION_INFO = 0x106  # macOS equivalent of Linux TCP_INFO


class ProtocolError(Exception):
    pass


async def read_varint(reader: asyncio.StreamReader) -> tuple[int, bytes]:
    value, raw = 0, b""
    for i in range(5):
        b = await reader.readexactly(1)
        raw += b
        value |= (b[0] & 0x7F) << (7 * i)
        if not b[0] & 0x80:
            return value, raw
    raise ProtocolError("VarInt too long")


def parse_varint(buf: bytes, pos: int) -> tuple[int, int]:
    value = 0
    for i in range(5):
        if pos >= len(buf):
            raise ProtocolError("truncated varint")
        b = buf[pos]
        pos += 1
        value |= (b & 0x7F) << (7 * i)
        if not b & 0x80:
            if value & (1 << 31):
                value -= 1 << 32
            return value, pos
    raise ProtocolError("VarInt too long")


def parse_string(buf: bytes, pos: int, max_len: int = 1024) -> tuple[str, int]:
    length, pos = parse_varint(buf, pos)
    if length < 0 or length > max_len * 4 or pos + length > len(buf):
        raise ProtocolError("bad string")
    return buf[pos:pos + length].decode("utf-8", "replace"), pos + length


def varint(n: int) -> bytes:
    n &= 0xFFFFFFFF
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def mc_string(s: str) -> bytes:
    data = s.encode("utf-8")
    return varint(len(data)) + data


def packet(pid: int, payload: bytes) -> bytes:
    body = varint(pid) + payload
    return varint(len(body)) + body


async def read_packet(reader: asyncio.StreamReader) -> tuple[bytes, bytes]:
    """Return (raw_bytes_including_length, body)."""
    length, raw_len = await read_varint(reader)
    if length <= 0 or length > MAX_HANDSHAKE:
        raise ProtocolError(f"bad packet length {length}")
    body = await reader.readexactly(length)
    return raw_len + body, body


def proxy_v2_header(src: tuple, dst: tuple) -> bytes:
    try:
        s_ip, d_ip = ipaddress.ip_address(src[0]), ipaddress.ip_address(dst[0])
    except ValueError:
        return PROXY_V2_SIG + b"\x20\x00\x00\x00"  # LOCAL command
    if s_ip.version == 4 and d_ip.version == 4:
        addr = s_ip.packed + d_ip.packed + struct.pack("!HH", src[1], dst[1])
        return PROXY_V2_SIG + b"\x21\x11" + struct.pack("!H", len(addr)) + addr
    if s_ip.version == 4:
        s_ip = ipaddress.IPv6Address("::ffff:" + str(s_ip))
    if d_ip.version == 4:
        d_ip = ipaddress.IPv6Address("::ffff:" + str(d_ip))
    addr = s_ip.packed + d_ip.packed + struct.pack("!HH", src[1], dst[1])
    return PROXY_V2_SIG + b"\x21\x21" + struct.pack("!H", len(addr)) + addr


def chat(text: str, color: str | None = None) -> dict:
    d: dict = {"text": text}
    if color:
        d["color"] = color
    return d


class MinecraftProxy:
    def __init__(self, manager: "Manager", host: str, port: int):
        self.m = manager
        self.host, self.port = host, port
        self.server: asyncio.base_events.Server | None = None
        self.active = 0
        self.total = 0
        self.bytes_up = 0
        self.bytes_down = 0
        self.per_server: dict[str, int] = {}
        self.started_at = time.time()
        self.error: str | None = None
        self.http_served = 0
        # server id -> lowercase player name -> client socket of the live game connection
        self.sessions: dict[str, dict[str, object]] = {}

    def player_pings(self, sid: str) -> dict[str, int | None]:
        """Network round-trip time (ms) of each player's connection, read on demand from the kernel.

        Players that reach the proxy over loopback (Bedrock players through Geyser, local tools)
        get ``None``: the loopback RTT says nothing about the player's real connection.
        """
        out: dict[str, int | None] = {}
        for name, sock in list(self.sessions.get(sid, {}).items()):
            out[name] = None if _is_loopback(sock) else tcp_rtt_ms(sock)
        return out

    def stats(self) -> dict:
        return {"host": self.host, "port": self.port, "active": self.active, "total": self.total,
                "bytes_up": self.bytes_up, "bytes_down": self.bytes_down, "per_server": dict(self.per_server),
                "listening": self.server is not None, "error": self.error, "packs_served": self.http_served}

    async def start(self) -> None:
        try:
            self.server = await asyncio.start_server(self._handle, self.host, self.port, reuse_address=True)
            log.info("Minecraft proxy listening on %s:%s", self.host, self.port)
        except OSError as exc:
            self.error = str(exc)
            log.error("Proxy could not bind %s:%s – %s", self.host, self.port, exc)

    async def stop(self) -> None:
        if self.server:
            self.server.close()
            with contextlib.suppress(Exception):
                await asyncio.wait_for(self.server.wait_closed(), 3)

    # ------------------------------------------------------------------
    async def _handle(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        peer = writer.get_extra_info("peername") or ("0.0.0.0", 0)
        sock = writer.get_extra_info("socket")
        if sock is not None:
            with contextlib.suppress(OSError):
                sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        self.total += 1
        try:
            await asyncio.wait_for(self._route(reader, writer, peer), HANDSHAKE_TIMEOUT)
        except (asyncio.TimeoutError, asyncio.IncompleteReadError, ProtocolError, ConnectionError):
            await self._close(writer)
        except _Piped as piped:
            await self._pipe(reader, writer, piped.r, piped.w, piped.inst, piped.player,
                             piped.track, piped.auth_name, piped.auth_ip)
        except _Http as req:
            await self._serve_http(writer, req.method, req.path)
        except Exception:
            log.exception("proxy error")
            await self._close(writer)

    async def _route(self, reader, writer, peer) -> None:
        first = await reader.readexactly(1)
        if first == b"\xfe":  # legacy (<1.7) server list ping – not supported, close politely
            await self._close(writer)
            return
        if first in (b"G", b"H"):
            # Plain HTTP on the Minecraft port – used to serve resource packs (GET/HEAD only).
            more = await reader.readexactly(3)
            if first + more in (b"GET ", b"HEAD"):
                head = first + more + await reader.readuntil(b"\r\n\r\n")
                if len(head) > 8192:
                    raise ProtocolError("http header too large")
                parts = head.split(b"\r\n", 1)[0].decode("latin-1").split(" ")
                raise _Http(parts[0], parts[1] if len(parts) > 1 else "/")
            # 'G'/'H' is also a valid single-byte VarInt (71/72) – continue as Minecraft
            length, raw_rest = first[0], b""
            body = more + await reader.readexactly(length - 3)
        else:
            length, raw_rest = await self._finish_varint(first, reader)
            if length <= 0 or length > MAX_HANDSHAKE:
                raise ProtocolError("bad handshake length")
            body = await reader.readexactly(length)
        handshake_raw = first + raw_rest + body
        pid, pos = parse_varint(body, 0)
        if pid != 0:
            raise ProtocolError("not a handshake")
        protocol, pos = parse_varint(body, pos)
        address, pos = parse_string(body, pos, 255)
        pos += 2  # port
        next_state, pos = parse_varint(body, pos)
        hostname = address.split("\x00", 1)[0].strip().rstrip(".").lower()

        inst = self.m.resolve_host(hostname)
        buffered = handshake_raw
        player = None
        player_uuid = None
        if next_state in (2, 3):  # login / transfer
            raw, login_body = await read_packet(reader)
            buffered += raw
            player_uuid = None
            with contextlib.suppress(ProtocolError, ValueError, IndexError):
                lpid, lpos = parse_varint(login_body, 0)
                if lpid == 0:
                    player, lpos = parse_string(login_body, lpos, 16)
                    if protocol >= 764 and len(login_body) >= lpos + 16:      # 1.20.2+: UUID always present
                        player_uuid = login_body[lpos:lpos + 16].hex()
                    elif protocol >= 761 and len(login_body) >= lpos + 17 and login_body[lpos] == 1:  # 1.19.3–1.20.1
                        player_uuid = login_body[lpos + 1:lpos + 17].hex()

        if inst is None:
            await self._reply_offline(reader, writer, next_state, "unknown", None, hostname)
            return

        target = inst
        auth_name, auth_ip = None, None
        lobby = getattr(self.m, "auth_lobby", None)
        # Offline-mode servers use the hidden Paper lobby. Online-mode servers
        # retain Mojang's normal authentication and do not pass through it.
        if player and not inst.online_mode:
            auth_ip = str(peer[0])
            from .auth_sessions import touch, valid
            if not valid(player, auth_ip):
                if not lobby or not lobby.running:
                    await self._reply_offline(reader, writer, next_state, "auth", inst, hostname)
                    return
                from .auth_sessions import set_pending
                set_pending(player, auth_ip)
                target = lobby
                auth_name = player
            else:
                # Session lifetime is 30 minutes from the last connection
                # activity; entering the target server refreshes it.
                touch(player, auth_ip)
                auth_name = player

        if player and self._not_whitelisted(inst, player):
            inst.record_attempt(player, None, "proxy")
        if player and inst is not None and target is inst:
            inst.bind_voice(player, player_uuid if next_state in (2, 3) else None)

        if target is inst and inst.state != "online":
            if next_state in (2, 3) and inst.request_start():
                mode = "waking"
            elif inst.state in ("starting", "installing"):
                mode = "starting"
            else:
                mode = "offline"
            await self._reply_offline(reader, writer, next_state, mode, inst, hostname)
            return

        try:
            port = target.port if target is lobby else target.cfg.internal_port
            up_r, up_w = await asyncio.wait_for(asyncio.open_connection("127.0.0.1", port), 5)
        except (OSError, asyncio.TimeoutError):
            await self._reply_offline(reader, writer, next_state, "starting", inst, hostname)
            return
        if target is inst and inst.cfg.proxy_protocol:
            local = writer.get_extra_info("sockname") or ("0.0.0.0", self.port)
            up_w.write(proxy_v2_header(peer, local))
        up_w.write(buffered)
        await up_w.drain()
        raise _Piped(up_r, up_w, inst, player if next_state in (2, 3) else None,
                     track=target is not lobby, auth_name=auth_name, auth_ip=auth_ip)

    @staticmethod
    def _not_whitelisted(inst: "ServerInstance", player: str) -> bool:
        """Record join attempts of players missing from the whitelist (when it is enabled)."""
        from . import players as pl
        if inst.props().get("white-list", "false") != "true":
            return False
        return not pl.contains(pl.read_list(inst.dir / "whitelist.json"), player)

    async def _finish_varint(self, first: bytes, reader) -> tuple[int, bytes]:
        value = first[0] & 0x7F
        raw = b""
        if not first[0] & 0x80:
            return value, raw
        for i in range(1, 5):
            b = await reader.readexactly(1)
            raw += b
            value |= (b[0] & 0x7F) << (7 * i)
            if not b[0] & 0x80:
                return value, raw
        raise ProtocolError("VarInt too long")

    def render(self, template: str, inst: "ServerInstance | None", hostname: str) -> str:
        if inst is None:
            values = {"name": hostname or "?", "motd": "", "address": hostname, "mc_version": "", "join_hint": ""}
        else:
            values = {"name": inst.cfg.name, "motd": inst.props().get("motd", inst.cfg.name),
                      "address": inst.address(), "mc_version": inst.cfg.mc_version,
                      "join_hint": " §8(dołącz, aby uruchomić)" if inst.cfg.start_on_join and inst.cfg.installed else ""}
        out = template
        for k, v in values.items():
            out = out.replace("{" + k + "}", str(v))
        return out.replace("\\n", "\n")

    async def _reply_offline(self, reader, writer, next_state: int, mode: str,
                             inst: "ServerInstance | None", hostname: str) -> None:
        s = self.m.settings
        try:
            if next_state == 1:
                await read_packet(reader)  # status request (empty packet 0x00)
                if mode == "unknown":
                    motd, version = f"§cNieznany serwer\n§7{hostname or '?'}", "§c✕"
                elif mode in ("starting", "waking"):
                    motd, version = s.motd_starting, s.version_starting
                else:
                    motd, version = s.motd_offline, s.version_offline
                status = {
                    "version": {"name": self.render(version, inst, hostname), "protocol": -1},
                    "players": {"max": 0, "online": 0},
                    "description": {"text": self.render(motd, inst, hostname)},
                }
                if inst:
                    icon = inst.dir / "server-icon.png"
                    if icon.exists() and icon.stat().st_size < 64 * 1024:
                        status["favicon"] = "data:image/png;base64," + base64.b64encode(icon.read_bytes()).decode()
                writer.write(packet(0, mc_string(json.dumps(status, ensure_ascii=False))))
                await writer.drain()
                with contextlib.suppress(Exception):  # ping (0x01 + long) – echo back
                    raw, body = await asyncio.wait_for(read_packet(reader), 3)
                    pid, pos = parse_varint(body, 0)
                    if pid == 1:
                        writer.write(packet(1, body[pos:pos + 8]))
                        await writer.drain()
            else:
                template = {"waking": s.kick_waking, "starting": s.kick_starting,
                            "auth": "§eTen serwer wymaga logowania. Połącz się ponownie, aby się zarejestrować lub zalogować."}.get(
                    mode, s.kick_offline if inst else "§cNieznany serwer: {name}")
                msg = {"text": self.render(template, inst, hostname)}
                writer.write(packet(0, mc_string(json.dumps(msg, ensure_ascii=False))))
                await writer.drain()
        finally:
            await self._close(writer)

    async def _serve_http(self, writer, method: str, path: str) -> None:
        """Minimal HTTP/1.1 responder for hosted resource packs (/rp/<server>/<token>/<pack>.zip)."""
        from . import resourcepacks as rpacks
        status, headers, file = "404 Not Found", {"Content-Type": "text/plain; charset=utf-8"}, None
        body = b"MineNode resource pack host\n"
        try:
            m = re.match(r"^/rp/([0-9a-f]{6,32})/([A-Za-z0-9_-]{8,64})/([0-9a-f]{12})\.zip(\?.*)?$", path)
            if method not in ("GET", "HEAD"):
                status, body = "405 Method Not Allowed", b"Method not allowed\n"
            elif m and (inst := self.m.instances.get(m.group(1))):
                try:
                    pack, p = rpacks.get(inst, m.group(3))
                    if hmac.compare_digest(pack["token"], m.group(2)) and p.exists():
                        status, file, body = "200 OK", p, b""
                        headers = {"Content-Type": "application/zip", "Content-Length": str(p.stat().st_size),
                                   "Cache-Control": "public, max-age=86400", "ETag": f'"{pack["sha1"]}"'}
                except FileNotFoundError:
                    pass
            if not file:
                headers["Content-Length"] = str(len(body))
            head = f"HTTP/1.1 {status}\r\n" + "".join(f"{k}: {v}\r\n" for k, v in headers.items()) + \
                "Connection: close\r\nServer: MineNode\r\n\r\n"
            writer.write(head.encode("latin-1"))
            if method != "HEAD":
                if file:
                    with open(file, "rb") as fh:
                        while chunk := fh.read(256 * 1024):
                            writer.write(chunk)
                            self.bytes_down += len(chunk)
                            await writer.drain()
                else:
                    writer.write(body)
            await writer.drain()
            self.http_served += 1 if file else 0
        except (ConnectionError, OSError):
            pass
        finally:
            await self._close(writer)

    async def _pipe(self, c_r, c_w, s_r, s_w, inst: "ServerInstance", player: str | None = None,
                    track: bool = True, auth_name: str | None = None, auth_ip: str | None = None) -> None:
        sid = inst.cfg.id if track else "auth-lobby"
        self.active += 1
        if track:
            self.per_server[sid] = self.per_server.get(sid, 0) + 1
        sock = c_w.get_extra_info("socket")
        key = player.lower() if player else None
        if track and key and sock is not None:
            self.sessions.setdefault(sid, {})[key] = sock

        async def copy(src: asyncio.StreamReader, dst: asyncio.StreamWriter, up: bool) -> None:
            try:
                while True:
                    data = await src.read(65536)
                    if not data:
                        break
                    if up:
                        self.bytes_up += len(data)
                    else:
                        self.bytes_down += len(data)
                    dst.write(data)
                    await dst.drain()
            except (ConnectionError, asyncio.CancelledError, OSError):
                pass
            finally:
                with contextlib.suppress(Exception):
                    if dst.can_write_eof():
                        dst.write_eof()

        try:
            t1 = asyncio.create_task(copy(c_r, s_w, True))
            t2 = asyncio.create_task(copy(s_r, c_w, False))
            done, pending = await asyncio.wait({t1, t2}, return_when=asyncio.FIRST_COMPLETED)
            # give the other direction a moment to flush (e.g. disconnect message)
            if pending:
                await asyncio.wait(pending, timeout=5)
            for t in pending:
                t.cancel()
        finally:
            self.active -= 1
            if track:
                self.per_server[sid] = max(0, self.per_server.get(sid, 1) - 1)
                live = self.sessions.get(sid, {})
                if key and live.get(key) is sock:  # a reconnect may already have replaced this entry
                    del live[key]
                    if not live:
                        self.sessions.pop(sid, None)
            if auth_name and auth_ip:
                lobby_obj = getattr(self.m, "auth_lobby", None)
                if lobby_obj:
                    lobby_obj.touch(auth_name, auth_ip)
            await self._close(c_w)
            await self._close(s_w)

    @staticmethod
    async def _close(writer: asyncio.StreamWriter) -> None:
        with contextlib.suppress(Exception):
            writer.close()
            await asyncio.wait_for(writer.wait_closed(), 2)


class _Http(Exception):
    def __init__(self, method: str, path: str):
        super().__init__()
        self.method, self.path = method, path


class _Piped(Exception):
    """Control-flow signal: the handshake was routed, start piping outside of the timeout scope."""

    def __init__(self, r, w, inst, player=None, track=True, auth_name=None, auth_ip=None):
        super().__init__()
        self.r, self.w, self.inst, self.player = r, w, inst, player
        self.track, self.auth_name, self.auth_ip = track, auth_name, auth_ip


def tcp_rtt_ms(sock) -> int | None:
    """Smoothed TCP round-trip time of a connected socket in milliseconds, or None if unavailable."""
    try:
        if sys.platform.startswith("linux"):
            # struct tcp_info: 8 bytes of u8 fields, then u32s; tcpi_rtt (µs) is the 16th u32.
            raw = sock.getsockopt(socket.IPPROTO_TCP, getattr(socket, "TCP_INFO", 11), 104)
            if len(raw) >= 72:
                rtt = struct.unpack_from("=I", raw, 68)[0] / 1000
                return max(1, round(rtt)) if rtt > 0 else None
        elif sys.platform == "darwin":
            # struct tcp_connection_info: 4 bytes of u8 fields, then u32s; tcpi_srtt (ms) at offset 44.
            raw = sock.getsockopt(socket.IPPROTO_TCP, TCP_CONNECTION_INFO, 64)
            if len(raw) >= 48:
                rtt = struct.unpack_from("=I", raw, 44)[0]
                return max(1, rtt) if rtt > 0 else None
    except (OSError, ValueError, struct.error):
        pass
    return None


def _is_loopback(sock) -> bool:
    try:
        return ipaddress.ip_address(sock.getpeername()[0].split("%", 1)[0]).is_loopback
    except (OSError, ValueError, IndexError, TypeError):
        return False
